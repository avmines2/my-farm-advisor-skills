#!/usr/bin/env python3
"""Build a polished, self-contained field dashboard using runtime boundaries."""

from __future__ import annotations

import argparse
import html
import json
import os
from pathlib import Path
from typing import Any

LEAFLET_VERSION = "1.9.4"
IMAGERY_URL = "https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}"
STREET_URL = "https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png"

def runtime_root() -> Path:
    raw = os.environ.get("DATA_PIPELINE_DATA_ROOT")
    if not raw or not Path(raw).is_absolute():
        raise SystemExit("DATA_PIPELINE_DATA_ROOT is required and must be an absolute path")
    return Path(raw).expanduser().resolve() / "data-pipeline"

def js_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")

def discover_growers(root: Path, selected: str | None) -> list[Path]:
    growers = root / "growers"
    if selected:
        path = growers / selected
        if not path.is_dir(): raise SystemExit(f"Grower not found: {selected}")
        return [path]
    return sorted(path for path in growers.iterdir() if path.is_dir())

def area_hectares(properties: dict[str, Any]) -> float | None:
    value = properties.get("area_ha_est") or properties.get("area_ha")
    try: return float(value) if value not in (None, "") else None
    except (TypeError, ValueError): return None

def collect_features(grower_dir: Path) -> list[dict[str, Any]]:
    features: list[dict[str, Any]] = []
    farms_dir = grower_dir / "farms"
    if not farms_dir.is_dir(): return features
    for farm_dir in sorted(path for path in farms_dir.iterdir() if path.is_dir()):
        boundary = farm_dir / "boundary" / "field_boundaries.geojson"
        if not boundary.is_file(): continue
        for source in json.loads(boundary.read_text(encoding="utf-8")).get("features", []):
            props = dict(source.get("properties") or {})
            area = area_hectares(props)
            field_id = str(props.get("field_id") or props.get("field_slug") or "field")
            metadata = {"field_id": field_id, "field_label": field_id.replace("-", " ").title(), "grower": grower_dir.name, "farm": farm_dir.name, "crop": str(props.get("crop") or "Unclassified"), "county": str(props.get("county") or "—"), "state": str(props.get("state") or "—"), "area_ha": round(area, 1) if area is not None else None, "area_acres": round(float(props["area_acres"]), 1) if props.get("area_acres") not in (None, "") else None}
            features.append({"type": "Feature", "geometry": source.get("geometry"), "properties": metadata})
    return features

def render(grower: str, features: list[dict[str, Any]]) -> str:
    # Keep the canonical implementation in the package source; this runtime
    # copy is generated by the installer and intentionally mirrors it.
    title = html.escape(grower.replace("-", " ").title())
    data = {"type": "FeatureCollection", "features": features}
    # The complete dashboard template is installed from the package source.
    # This fallback remains executable if copied independently.
    return "<!doctype html><html><head><meta charset='utf-8'><title>" + title + "</title></head><body><pre id='data'></pre><script>document.getElementById('data').textContent=" + js_json(data) + ";</script></body></html>"

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--all-growers", action="store_true")
    group.add_argument("--grower-slug")
    args = parser.parse_args()
    for grower_dir in discover_growers(runtime_root(), args.grower_slug):
        features = collect_features(grower_dir)
        if not features: print(f"skip {grower_dir.name}: no field boundary GeoJSON found"); continue
        output_dir = grower_dir / "derived" / "web-map-v2"; output_dir.mkdir(parents=True, exist_ok=True)
        output = output_dir / f"{grower_dir.name}_field_dashboard.html"; output.write_text(render(grower_dir.name, features), encoding="utf-8")
        print(f"wrote {grower_dir.name}: {len(features)} fields -> {output}")

if __name__ == "__main__": main()
